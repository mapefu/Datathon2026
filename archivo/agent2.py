def _f(x, default=float("nan")):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return default
    return v if math.isfinite(v) else default


def _parse_ts(ts):
    try:
        return datetime(ts.year, ts.month, ts.day, ts.hour, ts.minute, ts.second)
    except Exception:
        pass
    try:
        return datetime.fromisoformat(str(ts).replace("Z", "+00:00")[:19])
    except Exception:
        return None


def _clearsky(dt):
    try:
        doy = dt.timetuple().tm_yday
        decl = math.radians(23.45 * math.sin(2.0 * math.pi * (doy + 284.0) / 365.0))
        ha = math.radians(15.0 * (dt.hour + 0.5 - 12.0))
        lat = math.radians(41.3869)
        s = (math.sin(lat) * math.sin(decl)
             + math.cos(lat) * math.cos(decl) * math.cos(ha))
        return max(0.0, s)
    except Exception:
        return 0.0


