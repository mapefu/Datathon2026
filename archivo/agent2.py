    def _lp(self, H):
        if ("full", H) not in self._lp_cache:
            I = sparse.identity(H, format="csr")
            D = I - sparse.eye(H, k=-1, format="csr")
            Z = sparse.csr_matrix((H, H))
            A_eq = sparse.hstack([-ETA * I, I / ETA, Z, D], format="csr")
            A_ub = sparse.hstack([I, -I, -I, Z], format="csr")
            self._lp_cache[("full", H)] = (A_eq, A_ub)
        return self._lp_cache[("full", H)]

    def _solve_lp(self, H, net, w, v, soc, cap, pmax):
        if self._t_total >= TIME_BUDGET_S:
            return None
        A_eq, A_ub = self._lp(H)
        cost = np.concatenate([np.zeros(H), np.zeros(H), w, np.zeros(H)])
        cost[3 * H + H - 1] -= v
        b_eq = np.zeros(H); b_eq[0] = soc
        b_ub = -np.clip(net, -NET_CAP, NET_CAP)
        bounds = ([(0.0, pmax)] * (2 * H) + [(0.0, None)] * H + [(0.0, cap)] * H)
        t0 = time.perf_counter()
        sol = linprog(cost, A_ub=A_ub, b_ub=b_ub, A_eq=A_eq, b_eq=b_eq,
                      bounds=bounds, method="highs")
        self._t_total += time.perf_counter() - t0
        return float(sol.x[0] - sol.x[H]) if sol.success else None

